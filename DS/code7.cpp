// Reletional operator

#include<iostream>
using namespace std;

int main()
{
    cout<< (3<5)<<"\n"; // true -> 1
    cout<< (3>5)<<"\n"; // false -> 0
    cout<< (3<=3)<<"\n"; // true -> 1
    cout<< (3>=3)<<"\n";

    cout<< (3==3)<<"\n";
    cout<< (3!=3)<<"\n";


    return 0;
}