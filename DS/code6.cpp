// Arithmatic operation

#include<iostream>
using namespace std;

int main()
{
    int a = 10, b = 5;

    cout<< "sum = "<< (a+b) <<"\n";
    cout<< "difference = "<< (a-b) <<"\n";
    cout<< "Product = "<< (a*b) <<"\n";
    cout<< "division = "<< (a/b) <<"\n";
    cout<< "Modulo = "<< (a%b) <<"\n";

    
    return 0;
}